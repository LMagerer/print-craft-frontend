// zod 4 returns `.default(value)` as-is without parsing it; `.prefault` parses it so nested defaults apply.
import { readFileSync, writeFileSync } from "node:fs";

const file = process.argv[2];
const src = readFileSync(file, "utf8");
writeFileSync(file, "// Generated by `npm run gen:api` — do not edit.\n" + src.replaceAll(".default({})", ".prefault({})"));
